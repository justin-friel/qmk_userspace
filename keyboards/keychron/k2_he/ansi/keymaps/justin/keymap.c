// NULL_BASE preserves the K2 HE's native dip switch layer numbering
// while allowing WIN_BASE to remain a mostly transparent ANSI overlay.
// It is NOT EXPOSED by any key.
enum layers_k2_he {
	MAC_BASE,	// 0 - Full Mac base.
	NULL_BASE,	// 1 - 100% transparent placeholder.
	WIN_BASE,	// 2 - Sparse ANSI overlay.
	NAV_FN,		// 3 - Shared navigation layer.
	SET_FN		// 4 - Shared settings layer.
};

